# Fallback weekly hours when a subject/level is not listed in the annexes.
DEFAULT_WEEKLY_HOURS = 2


# ---------------------------------------------------------------------------
# Minimum grading norms per quarter per student per subject
# ---------------------------------------------------------------------------
# Band table: (min weekly hours, min grades per quarter)
#   8-10 h/week -> 14 grades
#   4-5  h/week -> 9 grades  (6-7 h also falls here: between the 9 and 14 bands)
#   3    h/week -> 7 grades
#   2    h/week -> 5 grades
#   1    h/week -> 3 grades
MIN_GRADES_BANDS = [
    (8, 14),
    (4, 9),
    (3, 7),
    (2, 5),
    (1, 3),
]


def quarter_minimum_grades(weekly_hours):
    """Return the minimum number of grades per quarter for a subject taught
    ``weekly_hours`` hours per week."""
    for min_hours, min_grades in MIN_GRADES_BANDS:
        if weekly_hours >= min_hours:
            return min_grades
    return 3


def grade_level(class_name):
    """Return the numeric grade level of a class name ('7-А' -> '7')."""
    m = re.match(r'^(\d+)', str(class_name or ''))
    return m.group(1) if m else ''


def weekly_hours(class_name, subject):
    """Weekly hours for ``subject`` in the grade level of ``class_name``."""
    level = grade_level(class_name)
    table = CURRICULUM_HOURS.get(level, {})
    return table.get(normalize_subject(subject), DEFAULT_WEEKLY_HOURS)


def quarter_min_norm(class_name, subject):
    """Minimum grades per quarter for ``subject`` in ``class_name``."""
    return quarter_minimum_grades(weekly_hours(class_name, subject))


def class_norms(class_name):
    """Return {subject: (weekly_hours, quarter_minimum)} for a class level."""
    level = grade_level(class_name)
    return {
        subj: (hours, quarter_minimum_grades(hours))
        for subj, hours in CURRICULUM_HOURS.get(level, {}).items()
    }
